DEFAULT = "midnight"
HEX = re.compile(r"#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b")


def _expand(h):
    h = h.lower()
    if len(h) in (3, 4):
        h = "".join(c * 2 for c in h)
    return h[:6], (h[6:] if len(h) == 8 else "")


def _var(role, alpha):
    return f"--c-{role}" + (f"-{alpha}" if alpha else "")


def tokenize(css, used):
    """Replace role colours with variables, outside :root blocks and outside the generated themes."""
    css = css.split(BEGIN)[0].rstrip() + "\n"
    out, pos = [], 0
    for m in re.finditer(r":root\s*\{[^}]*\}", css):       # leave the existing variable definitions alone
        out.append(_sub(css[pos:m.start()], used))
        out.append(m.group(0))
        pos = m.end()
    out.append(_sub(css[pos:], used))
    return "".join(out)


def _sub(text, used):
    def rep(m):
        rgb, alpha = _expand(m.group(1))
        role = ROLES.get(rgb)
        if not role:
            return m.group(0)
        used.add((role, alpha))
        return f"var({_var(role, alpha)})"
    return HEX.sub(rep, text)


def blocks(kind, used):
    lines = [BEGIN]
    for name, th in THEMES.items():
        if kind in th.get("skip", ()):      # this theme leaves these screens on the default (Midnight)
            continue
        sel = ":root" if name == DEFAULT else f':root[data-theme="{name}"]'
        decl = [f"{_var(r, a)}: {th['roles'][r]}{a};" for r, a in sorted(used)]
        decl += [f"{k}: {v};" for k, v in (th.get("named", {}).get(kind) or {}).items()]
        if name == DEFAULT:          # Midnight also applies with no data-theme at all
            sel = f':root, :root[data-theme="{name}"]'
        lines.append(f"{sel} {{ " + " ".join(decl) + " }")
        if th.get("extra"):
            lines.append(th["extra"])
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    for f in FILES:
        p = WEB / f
        used = set()
        css = tokenize(p.read_text(encoding="utf-8"), used)
        # variables already written as var(--c-...) by an earlier run count too
        for role, alpha in re.findall(r"var\(--c-([a-z0-9]+)(?:-([0-9a-f]{2}))?\)", css):
            used.add((role, alpha))
        p.write_text(css + "\n" + blocks(f.split(".")[0], used), encoding="utf-8", newline="\n")
        print(f"{f}: {len(used)} colour variables, {len(THEMES)} themes")


if __name__ == "__main__":
    main()
